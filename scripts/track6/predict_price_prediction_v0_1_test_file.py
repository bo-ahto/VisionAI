#!/usr/bin/env python3
"""Run runnable price predictions for the v0.1 new artwork feature file.

이 스크립트의 목적
-----------------
운영에서 들어온 무가격 작품 CSV를 `extract_price_prediction_v0_1_features.py`로
피처화한 뒤, 현재 저장소에서 즉시 실행 가능한 가격 예측값을 만든다.

주의할 점
---------
`price_prediction_v0.1`의 중간 리포트 기준 1순위 Warm 후보는 다음 결합식이다.

    pred_log = 0.70 * svc_numeric_seed_mean
             + 0.30 * pp_v8_compact_blend_mape_guarded

다만 `pp_v8_compact_blend_mape_guarded`는 검증/테스트 split에서 만든 실험
예측값 조합으로 남아 있고, 신규 데이터에 바로 적용할 단일 모델 artifact가
아직 저장되어 있지 않다. 따라서 이 스크립트는 그 결합식을 v0.1 최종 예측으로
가장하지 않는다.

대신 다음 두 값을 산출한다.

1. `svc_group_median_proxy`
   - 이미 생성된 Warm 유사 작품 기반 가격 피처의 로그 중앙값을 가격으로 복원.
   - v0.1 Warm 후보의 70% 축과 가장 가까운, 지금 바로 재현 가능한 값.
2. `legacy_warm_huber_baseline`
   - `legacy_artifacts/track6_warm_huber.joblib`로 실행하는 이전 baseline 모델.
   - v0.1 1순위 후보는 아니며, 파이프라인 smoke test/비교 기준으로만 사용.

가격 단위
---------
학습 target은 `ln_price_krw`이므로 모델 출력은 로그 원화 가격이다.
`exp(pred_log)`로 원화 가격을 복원하고, 외화 표시는 아래 고정 환산 기준으로
나눈다. 이 환산표는 2026-06-04 신규 테스트 준비 스크립트의 기준과 맞춘다.
"""
from __future__ import annotations

import argparse
import json
import math
from datetime import datetime
from pathlib import Path
from typing import Any

import joblib
import numpy as np
import pandas as pd


FX_KRW_PER_UNIT = {
    "USD": 1380.0,
    "EUR": 1530.0,
    "GBP": 1780.0,
    "HKD": 178.0,
    "JPY": 9.5,
}


def find_repo_root(start: Path) -> Path:
    """스크립트 위치와 무관하게 VisionAI repo root를 찾는다."""
    for current in [start, *start.parents]:
        if (current / "models" / "track6").exists() and (current / "scripts" / "track6").exists():
            return current
    raise RuntimeError(f"Could not find repository root from {start}")


REPO = find_repo_root(Path(__file__).resolve())
MODEL_ROOT = REPO / "models" / "track6" / "price_prediction_v0.1"
DEFAULT_FEATURE_DIR = MODEL_ROOT / "data" / "evaluation" / "test_new_artworks_test_noprice_0604_features"
DEFAULT_OUTPUT_DIR = MODEL_ROOT / "data" / "evaluation" / "test_new_artworks_test_noprice_0604_predictions"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Run runnable v0.1 price prediction outputs for the generated feature files."
    )
    parser.add_argument(
        "--feature-dir",
        type=Path,
        default=DEFAULT_FEATURE_DIR,
        help="Feature directory generated by extract_price_prediction_v0_1_features.py.",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Directory where prediction outputs will be written.",
    )
    return parser.parse_args()


def safe_exp(log_values: pd.Series | np.ndarray) -> np.ndarray:
    """로그 가격을 원화 가격으로 복원한다.

    매우 큰 값으로 인한 overflow를 피하기 위해 현실적인 범위에서 clip한다.
    """
    arr = np.asarray(log_values, dtype=float)
    return np.exp(np.clip(arr, math.log(1_000.0), math.log(1_000_000_000_000.0)))


def add_fx_columns(frame: pd.DataFrame, source_col: str, prefix: str) -> None:
    """원화 가격 컬럼에서 외화 환산 컬럼을 추가한다."""
    krw = pd.to_numeric(frame[source_col], errors="coerce")
    for currency, krw_per_unit in FX_KRW_PER_UNIT.items():
        frame[f"{prefix}_{currency.lower()}"] = krw / krw_per_unit


def price_summary(values: pd.Series | np.ndarray) -> dict[str, float]:
    """보고용 가격 분포 요약을 만든다."""
    arr = pd.Series(values).replace([np.inf, -np.inf], np.nan).dropna()
    if arr.empty:
        return {"n": 0}
    return {
        "n": int(arr.size),
        "min": float(arr.min()),
        "p10": float(arr.quantile(0.10)),
        "median": float(arr.median()),
        "p90": float(arr.quantile(0.90)),
        "max": float(arr.max()),
    }


def load_legacy_model(path: Path) -> Any | None:
    """저장된 baseline artifact를 읽는다. 없으면 None으로 두고 예측을 생략한다."""
    if not path.exists():
        return None
    return joblib.load(path)


def predict_legacy_pipeline(model: Any, frame: pd.DataFrame) -> np.ndarray:
    """sklearn pipeline이 요구하는 feature_names_in_ 기준으로 예측한다."""
    features = list(getattr(model, "feature_names_in_", []))
    if not features:
        raise ValueError("Legacy model does not expose feature_names_in_.")
    missing = [col for col in features if col not in frame.columns]
    if missing:
        raise ValueError(f"Missing required columns for legacy model: {missing}")
    X = frame[features].copy()

    # legacy artifact 학습 당시 boolean/categorical 값이 CSV를 거치며 문자열로 들어갔다.
    # 신규 피처 파일은 boolean dtype을 유지하므로, 그대로 넣으면 OneHotEncoder가
    # np.True_를 새로운 label로 판단한다. 학습 범주와 맞추기 위해 범주형 컬럼만 문자열화한다.
    prep = getattr(model, "named_steps", {}).get("prep")
    if prep is not None and hasattr(prep, "transformers_"):
        for name, _transformer, cols in prep.transformers_:
            if name == "cat":
                for col in cols:
                    if col in X.columns:
                        X[col] = X[col].astype(str)
    return np.asarray(model.predict(X), dtype=float)


def build_warm_predictions(features: pd.DataFrame, model_root: Path) -> pd.DataFrame:
    """Warm 행의 실행 가능한 가격 예측값을 만든다."""
    out_cols = [
        "_v01_row_id",
        "_track6_row_id",
        "slug",
        "title",
        "artist_name",
        "artist_slug",
        "matched_train_artist",
        "artist_key",
        "artist_match_source",
        "artist_match_status",
        "warm_cold_route",
        "artwork_url",
        "width_cm",
        "height_cm",
        "depth_cm",
        "area_cm2",
        "log_area",
        "medium_category",
        "support_category",
        "medium_support_bucket",
        "svc_group_level",
        "svc_coverage_tier",
        "svc_group_n",
    ]
    out = features[[col for col in out_cols if col in features.columns]].copy()
    out["exact_v01_primary_policy_runnable"] = False
    out["exact_v01_primary_policy_note"] = (
        "PP-SVC3 70:30 결합식의 PP-V8 component가 신규 데이터용 단일 artifact로 저장되어 있지 않음"
    )

    # 현재 피처 파일만으로 즉시 복원 가능한 유사 작품 기반 가격 피처.
    out["svc_group_median_pred_log"] = pd.to_numeric(
        features["svc_group_log_price_median"], errors="coerce"
    )
    out["svc_group_q25_log"] = pd.to_numeric(features["svc_group_log_price_q25"], errors="coerce")
    out["svc_group_q75_log"] = pd.to_numeric(features["svc_group_log_price_q75"], errors="coerce")
    out["svc_group_median_pred_price_krw"] = safe_exp(out["svc_group_median_pred_log"])
    out["svc_group_q25_price_krw"] = safe_exp(out["svc_group_q25_log"])
    out["svc_group_q75_price_krw"] = safe_exp(out["svc_group_q75_log"])
    add_fx_columns(out, "svc_group_median_pred_price_krw", "svc_group_median_pred_price")

    # 이전 baseline Warm Huber 모델. v0.1 현 1순위 후보는 아니므로 명칭에 baseline을 명시한다.
    warm_model = load_legacy_model(model_root / "legacy_artifacts" / "track6_warm_huber.joblib")
    if warm_model is not None and len(features) > 0:
        legacy_pred_log = predict_legacy_pipeline(warm_model, features)
        out["legacy_warm_huber_pred_log"] = legacy_pred_log
        out["legacy_warm_huber_pred_price_krw"] = safe_exp(legacy_pred_log)
        add_fx_columns(out, "legacy_warm_huber_pred_price_krw", "legacy_warm_huber_pred_price")
        out["legacy_warm_huber_status"] = "runnable_baseline_not_v0_1_primary"
    else:
        out["legacy_warm_huber_status"] = "artifact_missing_or_empty_input"

    return out


def build_cold_predictions(features: pd.DataFrame, model_root: Path) -> pd.DataFrame:
    """Cold 행이 있을 때 이전 LightGBM baseline 예측을 만든다.

    이번 2026-06-04 no-price 파일은 전체가 Warm으로 라우팅되어 이 함수 결과가
    빈 파일이 되는 것이 정상이다.
    """
    if features.empty:
        return features.copy()
    out = features.copy()
    out["exact_v01_primary_policy_runnable"] = False
    out["exact_v01_primary_policy_note"] = (
        "Cold v0.1 LightGBM Quantile + qwidth 보정 단일 artifact가 아직 저장되어 있지 않음"
    )
    cold_model = load_legacy_model(model_root / "legacy_artifacts" / "track6_cold_lightgbm.joblib")
    if cold_model is not None:
        legacy_pred_log = predict_legacy_pipeline(cold_model, features)
        out["legacy_cold_lightgbm_pred_log"] = legacy_pred_log
        out["legacy_cold_lightgbm_pred_price_krw"] = safe_exp(legacy_pred_log)
        add_fx_columns(out, "legacy_cold_lightgbm_pred_price_krw", "legacy_cold_lightgbm_pred_price")
        out["legacy_cold_lightgbm_status"] = "runnable_baseline_not_v0_1_reference"
    else:
        out["legacy_cold_lightgbm_status"] = "artifact_missing"
    return out


def write_readme(output_dir: Path, summary: dict[str, Any]) -> None:
    fx_lines = "\n".join(
        f"- 1 {currency} = {krw_per_unit:,.1f} KRW" for currency, krw_per_unit in FX_KRW_PER_UNIT.items()
    )
    text = f"""# 2026-06-04 신규 무가격 테스트 가격 예측 결과

- 생성일: {summary['created_at']}
- 입력 피처 폴더: `{summary['feature_dir']}`
- 전체 행: {summary['total_rows']:,}
- Warm 행: {summary['warm_rows']:,}
- Cold 행: {summary['cold_rows']:,}

## 생성 파일

| 파일 | 설명 |
|---|---|
| `predictions_all.csv` | Warm/Cold 실행 가능 예측값 통합 파일 |
| `warm_predictions.csv` | Warm 행 예측값 |
| `cold_predictions.csv` | Cold 행 예측값. 이번 파일은 0건 |
| `prediction_summary.json` | 실행 요약과 가격 분포 |

## 예측값 해석

- `svc_group_median_pred_price_krw`: 유사 작품 기반 가격 피처의 중앙값 예측. 현재 피처 파일만으로 바로 산출 가능한 값
- `legacy_warm_huber_pred_price_krw`: 이전 Warm Huber baseline artifact 예측. v0.1 현재 1순위 후보가 아니라 비교 기준
- `exact_v01_primary_policy_runnable`: 정확한 v0.1 1순위 결합식을 신규 데이터에 바로 실행할 수 있는지 여부

## 환산 기준

예측 가격의 기준 단위는 원화(KRW)다. 외화 표시는 다음 고정 환산 기준으로 나누어 계산했다.

{fx_lines}
"""
    (output_dir / "README.md").write_text(text, encoding="utf-8")


def main() -> None:
    args = parse_args()
    feature_dir = args.feature_dir.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)

    all_features = pd.read_csv(feature_dir / "features_all_v0_1.csv", low_memory=False)
    warm_features = pd.read_csv(feature_dir / "warm_features_v0_1.csv", low_memory=False)
    cold_features = pd.read_csv(feature_dir / "cold_features_v0_1.csv", low_memory=False)

    warm_predictions = build_warm_predictions(warm_features, MODEL_ROOT)
    cold_predictions = build_cold_predictions(cold_features, MODEL_ROOT)
    predictions_all = pd.concat([warm_predictions, cold_predictions], ignore_index=True, sort=False)

    warm_predictions.to_csv(output_dir / "warm_predictions.csv", index=False)
    cold_predictions.to_csv(output_dir / "cold_predictions.csv", index=False)
    predictions_all.to_csv(output_dir / "predictions_all.csv", index=False)

    summary: dict[str, Any] = {
        "created_at": datetime.now().isoformat(timespec="seconds"),
        "feature_dir": str(feature_dir),
        "output_dir": str(output_dir),
        "total_rows": int(len(all_features)),
        "warm_rows": int(len(warm_features)),
        "cold_rows": int(len(cold_features)),
        "price_unit": "KRW",
        "fx_krw_per_unit": FX_KRW_PER_UNIT,
        "exact_v01_primary_policy_status": "not_directly_runnable_until_component_artifactization",
        "exact_v01_primary_policy_reason": (
            "Warm PP-SVC3의 30% PP-V8 component와 Cold qwidth 보정이 신규 데이터용 단일 artifact로 저장되어 있지 않음"
        ),
        "runnable_outputs": {
            "warm_svc_group_median_proxy": "svc_group_median_pred_price_krw",
            "warm_legacy_huber_baseline": "legacy_warm_huber_pred_price_krw",
        },
        "price_summary_krw": {
            "svc_group_median": price_summary(warm_predictions.get("svc_group_median_pred_price_krw", [])),
            "legacy_warm_huber": price_summary(warm_predictions.get("legacy_warm_huber_pred_price_krw", [])),
        },
        "output_files": {
            "all": str(output_dir / "predictions_all.csv"),
            "warm": str(output_dir / "warm_predictions.csv"),
            "cold": str(output_dir / "cold_predictions.csv"),
            "summary": str(output_dir / "prediction_summary.json"),
            "readme": str(output_dir / "README.md"),
        },
    }
    (output_dir / "prediction_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    write_readme(output_dir, summary)

    print(json.dumps(summary, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
